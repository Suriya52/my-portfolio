// Data Types 

#include<stdio.h>
int main(){
     // integer value, Variable a storing the value of 5.
    int a=5;
    printf("%d",a); // %d is Formate specifier. Shows what type of data it is. %d for integer
    // output : 5


    float b=1.2;   
    printf("%f",b);  // %f for float 
    // output : 1.200000

    char c='S';   // store only one character or any other special Symblos in the key board.
    printf("%c",c);    // %c for Character
    // output : S

    double d=2.777777777777;
    printf("%lf",d);    // %lf for double. lf - long float.
    // output : 2.777778
}